function mirrorRows(rows) {
  return rows.map((r) => r + [...r].reverse().join(''));
}

const CACHE = new Map();

/** 返回一个内联 SVG 字符串；颜色跟随 currentColor */
export function icon(name, { size = 12, className = '' } = {}) {
  const key = `${name}:${size}:${className}`;
  if (CACHE.has(key)) return CACHE.get(key);
  const rows = ART[name] || ART.star;
  const rects = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let w = 1;
        while (row[x + w] === '#') w += 1;
        rects.push(`<rect x="${x}" y="${y}" width="${w}" height="1"/>`);
        x += w;
      } else x += 1;
    }
  });
  const svg =
    `<svg class="px-icon ${className}" viewBox="0 0 ${GRID} ${GRID}" width="${size}" height="${size}" ` +
    `shape-rendering="crispEdges" fill="currentColor" aria-hidden="true" focusable="false">${rects.join('')}</svg>`;
  CACHE.set(key, svg);
  return svg;
}

export function iconMirrored(name, opts) {
  const rows = mirrorRows(ART[name] || ART.star);
  const rects = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let w = 1;
        while (row[x + w] === '#') w += 1;
        rects.push(`<rect x="${x}" y="${y}" width="${w}" height="1"/>`);
        x += w;
      } else x += 1;
    }
  });
  const size = opts?.size ?? 12;
  return (
    `<svg class="px-icon ${opts?.className ?? ''}" viewBox="0 0 ${GRID} ${GRID}" width="${size}" height="${size}" ` +
    `shape-rendering="crispEdges" fill="currentColor" aria-hidden="true" focusable="false">${rects.join('')}</svg>`
  );
}

/** 校验所有图标的网格尺寸，开发期用 */
export function validateIcons() {
  const bad = [];
  for (const [name, rows] of Object.entries(ART)) {
    if (rows.length !== GRID) bad.push(`${name}: ${rows.length} 行`);
    rows.forEach((r, i) => {
      if (r.length !== GRID) bad.push(`${name} 第 ${i} 行宽度 ${r.length}`);
      if (/[^.#]/.test(r)) bad.push(`${name} 第 ${i} 行有非法字符`);
    });
  }
  if (bad.length) console.warn('[像素图标尺寸不齐]', bad);
  return bad;
}
